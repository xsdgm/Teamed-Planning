    aggregate = report.get("aggregate", {})
    provenance = report.get("provenance", {})
    title = ("VTemp rolling200 + v9 接口检查（非正式验证成绩）" if smoke else
             "WildScenes VTemp rolling200 + v9 二维实景迁移压力测试" if stress else "WildScenes VTemp rolling200 + v9 二维验证")
