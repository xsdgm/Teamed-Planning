def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", type=Path, required=True)
    parser.add_argument("--results", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--raw-dir", type=Path)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--geometry-audit", type=Path, help="Optional independent 1.5m endpoint connectivity audit JSON")
    args = parser.parse_args()
    cases_path, results_path = args.cases.resolve(), args.results.resolve()
    cases = json.loads(cases_path.read_text())
    map_path = (cases_path.parent / cases["map_npz"]).resolve()
    report, runs = load_runs(results_path, cases)
    provenance = report.get("provenance", {})
    metadata = cases.get("metadata", {})
    sequence = cases.get("sequence", metadata.get("sequence", "WildScenes"))
    smoke = bool(metadata.get("synthetic_smoke_only") or provenance.get("settings", {}).get("max_steps") is not None)
    map_metadata_path = map_path.parent / "map_metadata.json"
    map_metadata = json.loads(map_metadata_path.read_text()) if map_metadata_path.exists() else {}
    audit_path = args.geometry_audit
    if audit_path is None:
        candidate = cases_path.parents[2] / "diagnostics/geometry_audit/final_endpoint_components_safety.json"
