def finite_json(value):
    if isinstance(value, dict):
        return {str(k): finite_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [finite_json(v) for v in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def image_data_url(image, kind="PNG"):
    stream = io.BytesIO()
    image.save(stream, format=kind, **({"quality": 82, "optimize": True} if kind == "JPEG" else {"optimize": True}))
    mime = "image/jpeg" if kind == "JPEG" else "image/png"
    return f"data:{mime};base64," + base64.b64encode(stream.getvalue()).decode()


def render_map(path):
    with np.load(path, allow_pickle=False) as source:
        known = source["known"].astype(bool)
        occupied = source["occupied"].astype(bool)
        resolution = float(source["resolution_m"])
        origin = source["origin_xy"].astype(float)
    rgb = np.full((*known.shape, 3), [32, 43, 43], dtype=np.uint8)
    rgb[known & ~occupied] = [215, 229, 202]
    rgb[occupied] = [58, 89, 68]
    picture = Image.fromarray(np.flipud(rgb))
    picture.thumbnail((2600, 2600), Image.Resampling.NEAREST)
    return dict(image=image_data_url(picture), origin_xy=origin.tolist(), resolution_m=resolution,
                width_m=known.shape[1] * resolution, height_m=known.shape[0] * resolution,
                shape=list(known.shape))


def collect_photos(raw_dir, sequence, count=6):
    if raw_dir is None or not raw_dir.exists():
        return []
    candidates = []
    for suffix in ("*.png", "*.jpg", "*.jpeg"):
        for path in raw_dir.rglob(suffix):
            relative = path.relative_to(raw_dir)
            parts = [part.lower() for part in relative.parts[:-1]]
            if any("label" in part or "semantic" in part or "annotation" in part for part in parts):
                continue
            if sequence and sequence not in str(relative):
                continue
            candidates.append(path)
    candidates.sort()
    if not candidates:
        return []
    selected = sorted(set(np.linspace(0, len(candidates) - 1, min(count, len(candidates))).astype(int).tolist()))
    photos = []
    for index in selected:
        path = candidates[index]
        with Image.open(path) as source:
            picture = ImageOps.exif_transpose(source).convert("RGB")
            picture.thumbnail((720, 480))
            photos.append(dict(path=str(path.relative_to(raw_dir)), image=image_data_url(picture, "JPEG")))
    return photos


def number(value, precision=1):
    return "—" if value is None else f"{value:.{precision}f}"


def load_runs(results_path, tasks):
    report = json.loads(results_path.read_text())
    provenance = report.get("provenance", {})
    settings = provenance.get("settings", {})
    if (settings.get("strategy") != "vtemp_rolling200" or settings.get("subgoal_radius") != 200
            or settings.get("subgoal_arrival") != 25):
        raise ValueError("Expected results with explicit VTemp rolling200 / arrival25 provenance")
    case_lookup = {case["id"]: case for case in tasks["cases"]}
    records = {record["id"]: record for record in report.get("records", [])}
    scheduled = report.get("scheduled", list(records.values()))
    runs = []
    for item in scheduled:
        identifier = item["id"]
        record = records.get(identifier, {})
        detail_path = results_path.parent / "cases" / f"{identifier}.json"
        detail = json.loads(detail_path.read_text()) if detail_path.exists() else {}
        if detail and (not report.get("signature") or detail.get("signature") != report["signature"]):
            raise ValueError(f"{identifier}: case signature differs from the evaluation report")
        if detail and detail.get("status") != "error":
            overrides = detail.get("evaluation_overrides", {})
            if overrides.get("strategy") != "vtemp_rolling200" or overrides.get("subgoal_radius") != 200:
                raise ValueError(f"{identifier}: expected explicit VTemp rolling200 run, not a no-subgoal baseline")
            if detail.get("protocol") != provenance.get("protocol"):
                raise ValueError(f"{identifier}: case protocol differs from the evaluation report")
            if (provenance.get("perception") is not None and
                    overrides.get("perception") != provenance["perception"]):
                raise ValueError(f"{identifier}: case perception differs from the evaluation report")
        case_id = item.get("case_id", detail.get("case_id", record.get("case_id")))
        case = case_lookup[case_id]
        summary = detail.get("summary", record.get("summary", {}))
        expected_clearance = provenance.get("settings", {}).get("ground_safety_distance")
        if expected_clearance is not None and detail and detail.get("status") != "error":
            observed = summary.get("planning_clearances", {})
            overrides = detail.get("evaluation_overrides", {})
            if (observed.get("ground_safety_distance") != expected_clearance or
                    overrides.get("ground_safety_distance") != expected_clearance or
                    summary.get("safety_clearance_m") != expected_clearance):
                raise ValueError(f"{identifier}: actual planning clearance differs from the evaluation report")
        trajectory = detail.get("trajectory", [])
        if not trajectory:
            trajectory = [dict(step=0, ground=[*case["start"], 0.], uavs=[])]
        runs.append(dict(id=identifier, case_id=case_id, case=case, summary=summary,
                         planning_safety_clearance_m=provenance.get("settings", {}).get("ground_safety_distance", 1.5),
                         trajectory=trajectory, status=detail.get("status", record.get("status", "not_run")),
                         sample_seed=detail.get("sample_seed", item.get("sample_seed")),
                         error=detail.get("error"),
                         subgoal_events=detail.get("subgoal_events", []),
                         collision_events=detail.get("raster_collision_events", [])))
    if not runs:
        raise ValueError("No scheduled runs in results")
    return report, runs


def evaluation_scope(cases, runs, map_metadata, geometry_audit):
    # Old reports predate the explicit override and used archived 1.5m planners.
    planning = sorted({float(run.get("planning_safety_clearance_m",
        run.get("summary", {}).get("planning_clearances", {}).get("ground_safety_distance", 1.5)))
        for run in runs})
    clearances = sorted({float(run["case"].get("reference_clearance_m", 1.5)) for run in runs})
    stress = any(float(run["case"].get("reference_clearance_m", 1.5)) <
                 float(run.get("planning_safety_clearance_m", run.get("summary", {}).get(
                     "planning_clearances", {}).get("ground_safety_distance", 1.5))) - 1e-9 for run in runs)
    note = ""
    if stress:
        reference = "/".join(number(value, 2).rstrip("0").rstrip(".") for value in clearances)
        margins = "/".join(f"{value:g}" for value in planning)
        note = (f"这是 VTemp rolling200 + v9 系统的实景迁移压力测试：参考路线按 {reference}m 物理净空建立，"
                f"本组规划净空为 {margins}m。物理可通行不代表规划约束下可解；"
                "失败不能单独归因于权重泛化能力。")
        selected_ids = {run["case_id"] for run in runs}
        audited = {row["id"]: row for row in geometry_audit if row.get("id") in selected_ids}
        if (planning == [1.5] and selected_ids and selected_ids <= set(audited)
                and all(not row["connected"] for row in audited.values())):
            note += "独立审计显示，本组全部任务的起终点在 1.5m 净空栅格中不连通。"
    assumptions = {
        "resolution_m": map_metadata.get("resolution_m", cases.get("metadata", {}).get("source_resolution_m")),
        "vehicle_envelope_height_m": map_metadata.get("vehicle_envelope_height_m"),
        "ground_interpolation_max_m": map_metadata.get("ground_interpolation_max_m"),
        "reference_clearances_m": clearances,
        "planning_safety_clearance_m": planning[0] if len(planning) == 1 else None,
        "planning_safety_clearances_m": planning,
    }
    return stress, note, assumptions


def perception_description(provenance):
    resolution = provenance.get("perception", {}).get("mapping_resolution_m", 2.)
    clearance = provenance.get("perception", {}).get("graph_clearance_m",
        provenance.get("settings", {}).get("ground_safety_distance", 1.5))
    if resolution >= 2.:
        return "局部感知：无人机24×24m、2m栅格，建图与策略共用12×12输入；地面车8×8m、0.5m栅格。"
    return (f"局部感知适配：无人机24×24m视野，{resolution:g}m精细栅格用于建图；"
            "v9策略及送达证据仍使用原12×12、2m栅格，地面车保持8×8m、0.5m。"
            f"未知区域仍阻挡，图节点及边要求{clearance:g}m净空。证据桥接仍受2m网格限制；"
            "这是新的双分辨率配置，结果不能混入旧2m正式实验。")


